function stagesThrough(
  current: ProductionJob["status"],
  overrides?: Partial<Record<string, ProductionStageTask>>,
): ProductionStageTask[] {
  if (current === "on_hold") {
    return PRODUCTION_STAGES.map((stage, index) => ({
      stage,
      status: index < 3 ? "completed" : index === 3 ? "in_progress" : "pending",
      completedAt: index < 3 ? `2025-07-${18 + index}T10:00:00Z` : undefined,
      ...overrides?.[stage],
    }));
  }

  const currentIndex = PRODUCTION_STAGES.indexOf(current);
  return PRODUCTION_STAGES.map((stage, index) => ({
    stage,
    status:
      index < currentIndex ? "completed" : index === currentIndex ? "in_progress" : "pending",
    completedAt: index < currentIndex ? `2025-07-${18 + index}T10:00:00Z` : undefined,
    ...overrides?.[stage],
  }));
}

