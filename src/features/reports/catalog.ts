import type { ReportCategory, ReportColumn, ReportDefinition, ReportId } from "@/types/report";

function col(
  key: string,
  label: string,
  type: ReportColumn["type"] = "text",
  align?: ReportColumn["align"],
): ReportColumn {
  return {
    key,
    label,
    type,
    align: align ?? (type === "number" || type === "currency" || type === "percent" ? "right" : "left"),
  };
}

