const REPORT_BY_ID = new Map(REPORT_DEFINITIONS.map((report) => [report.id, report]));

export function getReportDefinition(id: string): ReportDefinition | undefined {
  return REPORT_BY_ID.get(id as ReportId);
}

export function getReportsByCategory(
  reports: ReportDefinition[] = REPORT_DEFINITIONS,
): { category: ReportCategory; label: string; reports: ReportDefinition[] }[] {
  return REPORT_CATEGORIES_ORDER.map((category) => ({
    category,
    label: REPORT_CATEGORY_LABELS[category],
    reports: reports.filter((report) => report.category === category),
  })).filter((group) => group.reports.length > 0);
}

const REPORT_CATEGORIES_ORDER: ReportCategory[] = [
  "sales",
  "operations",
  "production",
  "inventory",
  "finance",
  "delivery",
  "customers",
  "products",
  "admin",
];
